#!/usr/bin/env python3
"""Invert the exact released Raise 2 Layer renderer's gamma/channel conversion.

No firmware is modified. Input is restricted to the official 1.5.0 side image.
The renderer loads its LUT at 0x10012c62, and red/green gain literals at
0x10012f68/0x10012f60. It rounds via float32 operations then truncates to integer.
"""
from pathlib import Path
import argparse
import hashlib
import struct

ROOT = Path(__file__).resolve().parents[1]
STOCK_SHA = 'd01083b72600f77226f815fcc0828dcc08fb215dd2a6fa12a5fb88890a940186'
BIAS = 0x10005000


def float32(value):
    return struct.unpack('<f', struct.pack('<f', value))[0]


def transfer_tables():
    image = (ROOT / 'build/vendor/keyscanner-v1.5.0.bin').read_bytes()
    assert hashlib.sha256(image).hexdigest() == STOCK_SHA
    table = image[0x100267a4 - BIAS:0x100268a4 - BIAS]
    gains = [struct.unpack_from('<f', image, address - BIAS)[0]
             for address in (0x10012f68, 0x10012f60)]
    return [[min(255, int(float32(value * gain))) for value in table] for gain in gains]


def generated_header():
    result = '''/* Generated by tools/generate-splash-color.py from official Raise 2 1.5.0.
 * Compensates Layer renderer gamma and channel gains; does not alter the side.
 * Desired values are linear RGB before the user's global brightness setting.
 * SPDX-License-Identifier: GPL-3.0-only
 */
#pragma once
#include <stdint.h>
namespace SplashColor {
'''
    for name, table in zip(('red', 'green'), transfer_tables()):
        inverse = [min(range(256), key=lambda raw: abs(table[raw] - value)) for value in range(256)]
        assert inverse[0] == 0
        result += 'static const uint8_t ' + name + '[256] = {\n'
        for start in range(0, 256, 16):
            result += '  ' + ','.join(str(v) for v in inverse[start:start+16]) + ',\n'
        result += '};\n'
    return result + '}  // namespace SplashColor\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = ROOT / 'src/SplashColor.h'
    generated = generated_header()
    if args.check:
        assert output.read_text() == generated, 'Regenerate SplashColor.h with this tool'
    else:
        output.write_text(generated)
